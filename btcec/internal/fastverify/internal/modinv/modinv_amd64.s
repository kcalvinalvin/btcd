// func divsteps62Var(eta int64, f0, g0 uint64, t *trans2x2) int64
// Register use: R8 f, R9 g, R10 u, R11 v, R12 q, R13 r, R14 eta, R15 i,
// BX the neginv256 table, CX shift counts, AX/DI/SI scratch.
TEXT ·divsteps62Var(SB), NOSPLIT, $0-40
	MOVQ eta+0(FP), R14
	MOVQ f0+8(FP), R8
	MOVQ g0+16(FP), R9
	MOVQ $1, R10
	XORQ R11, R11
	XORQ R12, R12
	MOVQ $1, R13
	MOVQ $62, R15
	LEAQ ·neginv256(SB), BX

divRound:
	// zeros = trailing zeros of g with the mask capping at i
	MOVQ $-1, AX
	MOVQ R15, CX
	SHLQ CL, AX
	ORQ R9, AX
	TZCNTQ AX, CX
	SHRQ CL, R9
	SHLQ CL, R10
	SHLQ CL, R11
	SUBQ CX, R14
	SUBQ CX, R15
	JZ divDone

	// swap and negate when eta is negative
	TESTQ R14, R14
	JNS divNoSwap
	NEGQ R14
	MOVQ R8, AX
	MOVQ R9, R8
	NEGQ AX
	MOVQ AX, R9
	MOVQ R10, AX
	MOVQ R12, R10
	NEGQ AX
	MOVQ AX, R12
	MOVQ R11, AX
	MOVQ R13, R11
	NEGQ AX
	MOVQ AX, R13

divNoSwap:
	// limit = min(eta+1, i), m = ((1 << limit) - 1) & 255
	LEAQ 1(R14), CX
	CMPQ R15, CX
	CMOVQLT R15, CX
	MOVQ $1, DI
	SHLQ CL, DI
	DECQ DI
	ANDQ $255, DI

	// w = (g * neginv256[(f >> 1) & 127]) & m
	MOVQ R8, AX
	SHRQ $1, AX
	ANDQ $127, AX
	MOVBLZX (BX)(AX*1), AX
	IMULQ R9, AX
	ANDQ DI, AX

	// g += f*w, q += u*w, r += v*w
	MOVQ R8, DI
	IMULQ AX, DI
	ADDQ DI, R9
	MOVQ R10, DI
	IMULQ AX, DI
	ADDQ DI, R12
	MOVQ R11, DI
	IMULQ AX, DI
	ADDQ DI, R13
	JMP divRound

divDone:
	MOVQ t+24(FP), DI
	MOVQ R10, 0(DI)
	MOVQ R11, 8(DI)
	MOVQ R12, 16(DI)
	MOVQ R13, 24(DI)
	MOVQ R14, ret+32(FP)
	RET


// func update62(d, e, f, gg *signed62, t *trans2x2, mi *modInfo, length int64)
// Applies the transition matrix to (d, e) modulo the modulus and to
// (f, g) exactly, in one call. One-operand IMUL forms the signed 128-bit
// products directly. Register roles: u, v, q, r in R8..R11, the d/e (then
// f/g) accumulator pairs in R14:R15 and BX:CX, md/me in R12/R13, AX/DX
// the multiply ports.
#define M62MASK $0x3FFFFFFFFFFFFFFF

TEXT ·update62(SB), NOSPLIT, $0-56
	MOVQ t+32(FP), AX
	MOVQ 0(AX), R8
	MOVQ 8(AX), R9
	MOVQ 16(AX), R10
	MOVQ 24(AX), R11
	MOVQ d+0(FP), SI
	MOVQ e+8(FP), DI

	// md and me from the sign masks of d and e.
	MOVQ 32(SI), AX
	SARQ $63, AX
	MOVQ 32(DI), DX
	SARQ $63, DX
	MOVQ R8, R12
	ANDQ AX, R12
	MOVQ R9, BX
	ANDQ DX, BX
	ADDQ BX, R12
	MOVQ R10, R13
	ANDQ AX, R13
	MOVQ R11, BX
	ANDQ DX, BX
	ADDQ BX, R13

	// cd = u*d0 + v*e0, ce = q*d0 + r*e0
	MOVQ 0(SI), AX
	IMULQ R8
	MOVQ AX, R14
	MOVQ DX, R15
	MOVQ 0(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 0(SI), AX
	IMULQ R10
	MOVQ AX, BX
	MOVQ DX, CX
	MOVQ 0(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX

	// Exact division corrections through the modulus inverse.
	MOVQ mi+40(FP), AX
	MOVQ 40(AX), AX
	IMULQ R14, AX
	ADDQ R12, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	SUBQ AX, R12
	MOVQ mi+40(FP), AX
	MOVQ 40(AX), AX
	IMULQ BX, AX
	ADDQ R13, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	SUBQ AX, R13

	MOVQ mi+40(FP), AX
	MOVQ 0(AX), AX
	IMULQ R12
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ mi+40(FP), AX
	MOVQ 0(AX), AX
	IMULQ R13
	ADDQ AX, BX
	ADCQ DX, CX
	SHRQ $62, R15, R14
	SARQ $62, R15
	SHRQ $62, CX, BX
	SARQ $62, CX

	// limb 1
	MOVQ 8(SI), AX
	IMULQ R8
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 8(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ mi+40(FP), AX
	MOVQ 8(AX), AX
	IMULQ R12
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 8(SI), AX
	IMULQ R10
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ 8(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ mi+40(FP), AX
	MOVQ 8(AX), AX
	IMULQ R13
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ R14, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 0(SI)
	SHRQ $62, R15, R14
	SARQ $62, R15
	MOVQ BX, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 0(DI)
	SHRQ $62, CX, BX
	SARQ $62, CX

	// limb 2
	MOVQ 16(SI), AX
	IMULQ R8
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 16(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ mi+40(FP), AX
	MOVQ 16(AX), AX
	IMULQ R12
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 16(SI), AX
	IMULQ R10
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ 16(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ mi+40(FP), AX
	MOVQ 16(AX), AX
	IMULQ R13
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ R14, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 8(SI)
	SHRQ $62, R15, R14
	SARQ $62, R15
	MOVQ BX, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 8(DI)
	SHRQ $62, CX, BX
	SARQ $62, CX

	// limb 3
	MOVQ 24(SI), AX
	IMULQ R8
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 24(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ mi+40(FP), AX
	MOVQ 24(AX), AX
	IMULQ R12
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 24(SI), AX
	IMULQ R10
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ 24(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ mi+40(FP), AX
	MOVQ 24(AX), AX
	IMULQ R13
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ R14, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 16(SI)
	SHRQ $62, R15, R14
	SARQ $62, R15
	MOVQ BX, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 16(DI)
	SHRQ $62, CX, BX
	SARQ $62, CX

	// limb 4
	MOVQ 32(SI), AX
	IMULQ R8
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 32(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ mi+40(FP), AX
	MOVQ 32(AX), AX
	IMULQ R12
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 32(SI), AX
	IMULQ R10
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ 32(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ mi+40(FP), AX
	MOVQ 32(AX), AX
	IMULQ R13
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ R14, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 24(SI)
	SHRQ $62, R15, R14
	SARQ $62, R15
	MOVQ BX, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, 24(DI)
	SHRQ $62, CX, BX
	SARQ $62, CX
	MOVQ R14, 32(SI)
	MOVQ BX, 32(DI)

	// (f, g) pass: exact division, no modulus terms, length limbs.
	MOVQ f+16(FP), SI
	MOVQ gg+24(FP), DI
	MOVQ 0(SI), AX
	IMULQ R8
	MOVQ AX, R14
	MOVQ DX, R15
	MOVQ 0(DI), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ 0(SI), AX
	IMULQ R10
	MOVQ AX, BX
	MOVQ DX, CX
	MOVQ 0(DI), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	SHRQ $62, R15, R14
	SARQ $62, R15
	SHRQ $62, CX, BX
	SARQ $62, CX
	MOVQ length+48(FP), R13
	MOVQ $1, R12

fgLoop:
	CMPQ R12, R13
	JGE fgDone
	MOVQ (SI)(R12*8), AX
	IMULQ R8
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ (DI)(R12*8), AX
	IMULQ R9
	ADDQ AX, R14
	ADCQ DX, R15
	MOVQ (SI)(R12*8), AX
	IMULQ R10
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ (DI)(R12*8), AX
	IMULQ R11
	ADDQ AX, BX
	ADCQ DX, CX
	MOVQ R14, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, -8(SI)(R12*8)
	SHRQ $62, R15, R14
	SARQ $62, R15
	MOVQ BX, AX
	MOVQ M62MASK, DX
	ANDQ DX, AX
	MOVQ AX, -8(DI)(R12*8)
	SHRQ $62, CX, BX
	SARQ $62, CX
	INCQ R12
	JMP fgLoop

fgDone:
	MOVQ R14, -8(SI)(R13*8)
	MOVQ BX, -8(DI)(R13*8)
	RET
