	VMOVDQU64.Z 0(R11), K1, Z17
	VMOVDQU64.Z 40(R11), K1, Z18
	VMOVDQU64 Z16, K1, 0(SP)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z19)
	BALIGN(Z31)
	ZEROACC
	MROWS(Z27, Z31)
	MERGE
	VPSLLQ $1, Z8, Z8
	VPSLLQ $1, Z10, Z10
	VPSLLQ $1, Z12, Z12
	REDTAIL2(Z19)
	REDFOLD(Z31)
	VMOVDQU64.Z 40(R8), K1, Z20
	BALIGN(Z16)
	ZEROACC
	MROWS(Z20, Z16)
	MERGE
	REDTAILW(Z31)
	VMOVDQU64 Z31, K1, 256(SP)
	REDFOLD(Z20)
	BALIGN(Z21)
	ZEROACC
	MROWS(Z21, Z21)
	MERGE
	REDTAIL2(Z20)
	REDFOLD(Z31)
	BALIGN(Z19)
	ZEROACC
	VMOVDQU64.Z 0(R8), K1, Z16
	MROWS(Z16, Z19)
	MERGE
	REDTAIL2(Z31)
	REDFOLD(Z16)
	BALIGN(Z27)
	ZEROACC
	MROWS(Z27, Z27)
	MERGE
	REDTAIL2(Z16)
	REDFOLD(Z27)
	BALIGN(Z19)
	ZEROACC
	MROWS(Z20, Z19)
	MERGE
	REDTAIL2(Z27)
	REDFOLD(Z20)
	BALIGN(Z27)
	ZEROACC
	MROWS(Z21, Z27)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	REDTAIL2(Z20)
	VMOVDQU64 Z19, K1, 64(SP)
