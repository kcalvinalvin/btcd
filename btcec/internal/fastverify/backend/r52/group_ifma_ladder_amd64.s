// func ladderRunIFMA(acc, gacc *jacobianPoint, ops []ladderOp) uint64
// Runs a precompiled ladder schedule in one call: the accumulator stays
// resident in Z21/Z27/Z31 across every op, the setup constants load once,
// and the G chain point lives in its caller memory through R11. Op kinds:
// 0 doubles the accumulator, 1 doubles it while adding an entry to the G
// chain with the two streams interleaved, 2 adds an entry to the
// accumulator. The doubling bodies never reduce D and F on their own:
// X3 = F - 2*D and T = 3*D - F form as column combinations of the two
// unreduced product forms through the ifmaCDF constant, saving both
// reduction tails. On a nonzero return, from a degenerate shared-x
// addition or an accumulated carry-pass leftover, both points may hold
// partial results and the caller must redo the schedule from saved
// copies.
TEXT ·ladderRunIFMA(SB), NOSPLIT, $384-48
	MOVQ acc+0(FP), DI
	MOVQ gacc+8(FP), R11
	MOVQ ops_base+16(FP), R9
	MOVQ ops_len+24(FP), R10
	IFMASETUP

	VMOVDQU64.Z 0(DI), K1, Z21  // acc X
	VMOVDQU64.Z 40(DI), K1, Z27 // acc Y
	VMOVDQU64.Z 80(DI), K1, Z31 // acc Z

ladderLoop:
	TESTQ R10, R10
	JZ ladderDone
	MOVQ 0(R9), AX
	MOVQ 8(R9), R8
	ADDQ $16, R9
	DECQ R10
	CMPQ AX, $1
	JB ladderD
	JE ladderDG

	// Accumulator addition: acc moves through the add-side registers.
	VMOVDQA64 Z21, Z17
	VMOVDQA64 Z27, Z18
	VMOVDQA64 Z31, Z16
	VMOVDQU64 Z16, K1, 0(SP)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z19)
	REDTAIL2(Z19)
	VMOVDQU64.Z 40(R8), K1, Z20
	ZEROACC
	MROWS(Z20, Z16)
	MERGE
	REDFOLD(Z20)
	REDTAIL2(Z20)
	BALIGN(Z19)
