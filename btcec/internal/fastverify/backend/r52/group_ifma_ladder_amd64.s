	REDTAIL2(Z20)
	VMOVDQU64 Z19, K1, 64(SP)
	VMOVDQU64 ifmaC2<>(SB), Z13
	VPADDQ Z13, Z16, Z16
	VPSUBQ Z17, Z16, Z16
	WEAKOUT2(Z16)
	VPTESTMQ Z16, Z16, K6
	KORTESTW K6, K6
	JEQ ladderBail
	VMOVDQU64 ifmaPrime<>(SB), Z13
	VPCMPEQQ Z13, Z16, K6
	KMOVW K6, AX
	CMPL AX, $0xFF
	JEQ ladderBail
	VMOVDQU64 ifmaC2<>(SB), Z13
	VPADDQ Z13, Z20, Z20
	VPSUBQ Z18, Z20, Z20
	PASSF2(Z20)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z19)
	REDTAIL2(Z19)
	BALIGN(Z19)
	ZEROACC
	MROWS(Z17, Z19)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	REDFOLD(Z17)
	REDTAIL2(Z17)
	ZEROACC
	MROWS(Z16, Z19)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	VMOVDQU64 Z19, K1, 128(SP)
	REDFOLD(Z19)
	REDTAIL2(Z19)
	VMOVDQU64.Z 0(SP), K1, Z13
	VPADDQ Z13, Z16, Z16
	PASSF2(Z16)
	BALIGN(Z19)
	ZEROACC
	MROWS(Z18, Z19)
	MERGE
	REDFOLD(Z18)
	REDTAIL2(Z18)
	VMOVDQU64 Z18, K1, 192(SP)
	BALIGN(Z20)
	ZEROACC
	MROWS(Z20, Z20)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	REDFOLD(Z18)
	REDTAIL2(Z18)
	VPSLLQ $1, Z17, Z0
	VMOVDQU64 ifmaC32<>(SB), Z13
	VPADDQ Z13, Z18, Z14
	VPSUBQ Z19, Z14, Z19
	VPSUBQ Z0, Z19, Z19
	VMOVDQU64 ifmaC512<>(SB), Z13
	VPADDQ Z13, Z17, Z14
	VPSUBQ Z19, Z14, Z17
	PASSF2(Z17)
	BALIGN(Z17)
	ZEROACC
	MROWS(Z20, Z17)
	MERGE
	VPSLLQ $1, Z8, Z8
	VPSLLQ $1, Z10, Z10
	VPSLLQ $1, Z12, Z12
	REDFOLD(Z20)
	REDTAIL2(Z20)
	WEAKOUT2(Z19)
	VMOVDQU64.Z 192(SP), K1, Z14
	VPSLLQ $1, Z14, Z0
	VMOVDQU64 ifmaC32<>(SB), Z13
	VPADDQ Z13, Z20, Z20
	VPSUBQ Z0, Z20, Z20
	WEAKOUT2(Z20)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z16)
	REDTAIL2(Z16)
	VMOVDQU64 ifmaC32<>(SB), Z13
	VMOVDQU64.Z 64(SP), K1, Z14
	VMOVDQU64.Z 128(SP), K1, Z15
	VPADDQ Z13, Z16, Z16
	VPSUBQ Z14, Z16, Z16
	VPSUBQ Z15, Z16, Z16
	WEAKOUT2(Z16)
	VMOVDQA64 Z19, Z21
	VMOVDQA64 Z20, Z27
	VMOVDQA64 Z16, Z31
	JMP ladderLoop

ladderD:
	BALIGN(Z31)
	ZEROACC
	MROWS(Z27, Z31)
	MERGE
	VPSLLQ $1, Z8, Z8
	VPSLLQ $1, Z10, Z10
	VPSLLQ $1, Z12, Z12
	REDFOLD(Z31)
	REDTAILW(Z31)
	VMOVDQU64 Z31, K1, 256(SP)
	BALIGN(Z21)
