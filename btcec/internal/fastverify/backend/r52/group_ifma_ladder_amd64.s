	PASSF2(Z20)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z19)
	REDTAIL2(Z19)
	BALIGN(Z19)
	ZEROACC
	MROWS(Z17, Z19)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	REDFOLD(Z17)
	REDTAIL2(Z17)
	ZEROACC
	MROWS(Z16, Z19)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	VMOVDQU64 Z19, K1, 128(SP)
	REDFOLD(Z19)
	REDTAIL2(Z19)
	VMOVDQU64.Z 0(SP), K1, Z13
	VPADDQ Z13, Z16, Z16
	PASSF2(Z16)
	BALIGN(Z19)
	ZEROACC
	MROWS(Z18, Z19)
	MERGE
	REDFOLD(Z18)
	REDTAIL2(Z18)
	VMOVDQU64 Z18, K1, 192(SP)
	BALIGN(Z20)
	ZEROACC
	MROWS(Z20, Z20)
	MERGE
	VPSLLQ $2, Z8, Z8
	VPSLLQ $2, Z10, Z10
	VPSLLQ $2, Z12, Z12
	REDFOLD(Z18)
	REDTAIL2(Z18)
	VPSLLQ $1, Z17, Z0
	VMOVDQU64 ifmaC32<>(SB), Z13
	VPADDQ Z13, Z18, Z14
	VPSUBQ Z19, Z14, Z19
	VPSUBQ Z0, Z19, Z19
	VMOVDQU64 ifmaC512<>(SB), Z13
	VPADDQ Z13, Z17, Z14
	VPSUBQ Z19, Z14, Z17
	PASSF2(Z17)
	BALIGN(Z17)
	ZEROACC
	MROWS(Z20, Z17)
	MERGE
	VPSLLQ $1, Z8, Z8
	VPSLLQ $1, Z10, Z10
	VPSLLQ $1, Z12, Z12
	REDFOLD(Z20)
	REDTAIL2(Z20)
	WEAKOUT2(Z19)
	VMOVDQU64.Z 192(SP), K1, Z14
	VPSLLQ $1, Z14, Z0
	VMOVDQU64 ifmaC32<>(SB), Z13
	VPADDQ Z13, Z20, Z20
	VPSUBQ Z0, Z20, Z20
	WEAKOUT2(Z20)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z16)
	REDTAIL2(Z16)
