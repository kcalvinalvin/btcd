	VMOVDQU64 Z27, K1, 320(SP)
	BALIGN(Z31)
	ZEROACC
	MROWS(Z31, Z31)
	MERGE
	VPSLLQ $3, Z8, Z0
	VPADDQ Z0, Z8, Z8
	VPSLLQ $3, Z10, Z0
	VPADDQ Z0, Z10, Z10
	VPSLLQ $3, Z12, Z0
	VPADDQ Z0, Z12, Z12
	REDFOLD(Z27)
	VPSLLQ $1, Z21, Z0
	VMOVDQU64 ifmaCDF<>(SB), Z13
	VPADDQ Z0, Z21, Z14
	VPADDQ Z13, Z14, Z21
	VPSUBQ Z27, Z21, Z21
	VPADDQ Z13, Z27, Z27
	VPSUBQ Z0, Z27, Z27
	REDTAIL2(Z21)
	BALIGN(Z21)
	ZEROACC
	MROWS(Z31, Z21)
	MERGE
	VPSLLQ $1, Z8, Z0
	VPADDQ Z0, Z8, Z8
	VPSLLQ $1, Z10, Z0
	VPADDQ Z0, Z10, Z10
	VPSLLQ $1, Z12, Z0
	VPADDQ Z0, Z12, Z12
	REDFOLD(Z31)
	REDTAIL2(Z31)
	REDTAILW(Z27)
	VMOVDQU64.Z 320(SP), K1, Z14
	VPSLLQ $3, Z14, Z0
	VMOVDQU64 ifmaC8<>(SB), Z13
	VPADDQ Z13, Z31, Z31
	VPSUBQ Z0, Z31, Z31
	WEAKOUT2(Z31)
	VMOVDQA64 Z27, Z21
	VMOVDQA64 Z31, Z27
	VMOVDQU64.Z 256(SP), K1, Z31
	JMP ladderLoop

