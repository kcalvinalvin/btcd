// func oddChainIFMA(table *[8]jacobianPoint, twoQ *affinePoint) uint64
// Fills table entries 1..7 with the chain table[i] = table[i-1] + twoQ,
// keeping the accumulator in the add-side registers across the seven
// additions and snapshotting each result. The chain never hits the
// degenerate case for a finite 2Q, but the shared bail contract still
// applies: on a nonzero return the caller redoes the chain op by op.
TEXT ·oddChainIFMA(SB), NOSPLIT, $384-24
	MOVQ table+0(FP), R9
	MOVQ twoQ+8(FP), R8
	IFMASETUP

	VMOVDQU64.Z 0(R9), K1, Z17  // X
	VMOVDQU64.Z 40(R9), K1, Z18 // Y
	VMOVDQU64.Z 80(R9), K1, Z16 // Z
	MOVQ $7, R10

oddChainLoop:
	ADDQ $128, R9
	VMOVDQU64 Z16, K1, 0(SP)
	BALIGN(Z16)
	ZEROACC
	MROWS(Z16, Z16)
	MERGE
	REDFOLD(Z19)
	REDTAIL2(Z19)
	VMOVDQU64.Z 40(R8), K1, Z20
	ZEROACC
	MROWS(Z20, Z16)
	MERGE
	REDFOLD(Z20)
	REDTAIL2(Z20)
	BALIGN(Z19)
	ZEROACC
	VMOVDQU64.Z 0(R8), K1, Z16
	MROWS(Z16, Z19)
	MERGE
	REDFOLD(Z16)
	REDTAIL2(Z16)
	ZEROACC
	MROWS(Z20, Z19)
	MERGE
	REDFOLD(Z20)
	REDTAIL2(Z20)
	VMOVDQU64 Z19, K1, 64(SP)
	VMOVDQU64 ifmaC2<>(SB), Z13
	VPADDQ Z13, Z16, Z16
	VPSUBQ Z17, Z16, Z16
	WEAKOUT2(Z16)
	VPTESTMQ Z16, Z16, K6
